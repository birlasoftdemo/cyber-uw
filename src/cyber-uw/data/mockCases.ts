function gap(
  partial: Omit<ControlGap, 'qualificationBucket'> & { qualificationBucket?: ControlGap['qualificationBucket'] },
): ControlGap {
  return {
    ...partial,
    qualificationBucket: partial.qualificationBucket ?? inferBucketFromControl(partial.control),
  }
}

function signedPackage(caseId: string, docCount: number, at: string): PackageSignOff {
  return {
    acceptedDocIds: Array.from({ length: docCount }, (_, i) => `${caseId}-doc-${i}`),
    signedAnswerKeys: ['*'],
    signedOffAt: at,
    signedOffBy: 'You (UW)',
  }
}

