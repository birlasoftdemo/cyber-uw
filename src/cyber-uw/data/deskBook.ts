import { buildPlatformCards } from './platformDemo'
import { defaultFormSignals, packageDocsFromNames } from './dossierPackage'
import { CYBER_PRODUCT_DEFAULTS } from './productIdentity'
import type { CyberCase, CyberDecision, SubmissionKind, VendorExposure } from '../types'

type DeskSeed = {
  id: string
  insured: string
  broker: string
  sector: string
  insuredAddress: string
  productCode: string
  productName: string
  revenueUsd: number
  limitRequestedUsd: number
  receivedAt: string
  policyStartAt: string
  policyEndAt: string
  completenessPct: number
  tier: CyberCase['tier']
  recommendation: CyberDecision
  decision: CyberDecision
  submissionKind: SubmissionKind
  signalScore: number
  workflowStage: number
  pasStatus?: CyberCase['pasStatus']
  summary: string
  vendors?: VendorExposure[]
}

function deskCase(seed: DeskSeed): CyberCase {
  const vendors = seed.vendors ?? [
    { vendor: 'Microsoft 365', category: 'SaaS / Identity', bookCount: 18, limitHint: 'OK' },
    { vendor: 'AWS', category: 'Cloud', bookCount: 12, limitHint: 'Within treaty soft cap' },
  ]
  return {
    id: seed.id,
    insured: seed.insured,
    broker: seed.broker,
    sector: seed.sector,
    insuredAddress: seed.insuredAddress,
    companyDescription: seed.summary,
    ...CYBER_PRODUCT_DEFAULTS,
    productCode: seed.productCode,
    productName: seed.productName,
    renewalApplicable: seed.submissionKind === 'renewal',
    revenueUsd: seed.revenueUsd,
    limitRequestedUsd: seed.limitRequestedUsd,
    receivedAt: seed.receivedAt,
    policyStartAt: seed.policyStartAt,
    policyEndAt: seed.policyEndAt,
    completenessPct: seed.completenessPct,
    tier: seed.tier,
    recommendation: seed.recommendation,
    decision: seed.decision,
    submissionKind: seed.submissionKind,
    signalScore: seed.signalScore,
    signalStatus: 'ready',
    pasStatus: seed.pasStatus ?? 'idle',
    workflowStage: seed.workflowStage,
    riskJudgments: {},
    gaps: [],
    appetiteHits: [],
    vendors,
    platformCards: buildPlatformCards(seed.id, vendors, seed.sector, seed.limitRequestedUsd),
    packageDocs: packageDocsFromNames(seed.id, [`${seed.id}_Cyber_Application.pdf`]),
    formSignals: defaultFormSignals(seed.id, {
      insured: seed.insured,
      sector: seed.sector,
      limitUsd: seed.limitRequestedUsd,
    }),
    dossierSummary: seed.summary,
    audit: [{ at: seed.receivedAt, actor: 'Intake Agent', action: 'Normalized submission' }],
  }
}

