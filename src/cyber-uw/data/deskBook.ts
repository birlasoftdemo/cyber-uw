function queueFillCase(seed: QueueFillSeed): CyberCase {
  const kind = seed.submissionKind ?? 'new_business'
  const day = Number(seed.id.slice(-2))
  const receivedAt = `2026-08-${String(10 + (day % 18)).padStart(2, '0')}T10:00:00Z`
  const policyStartAt = `2026-09-${String(1 + (day % 27)).padStart(2, '0')}`
  const policyEndAt = `2027-09-${String(1 + (day % 27)).padStart(2, '0')}`
  const shared = {
    id: seed.id,
    insured: seed.insured,
    broker: seed.broker,
    sector: seed.sector,
    insuredAddress: seed.insuredAddress,
    productCode: seed.productCode,
    productName: seed.productName,
    revenueUsd: seed.revenueUsd,
    limitRequestedUsd: seed.limitRequestedUsd,
    receivedAt,
    policyStartAt,
    policyEndAt,
    submissionKind: kind,
    tier: 3 as const,
  }

  switch (seed.bucket) {
    case 'new':
      return deskCase({
        ...shared,
        completenessPct: 62 + (day % 10),
        recommendation: 'pending',
        decision: 'pending',
        signalScore: 55 + (day % 15),
        workflowStage: 0,
        summary: `${seed.insured} waiting in New Submissions for first triage.`,
      })
    case 'broker':
      return deskCase({
        ...shared,
        completenessPct: 70 + (day % 8),
        recommendation: 'pending',
        decision: 'pending',
        signalScore: 58 + (day % 12),
        workflowStage: 1,
        missingDocs: ['Loss Runs', 'InfoSec Questionnaire'],
        summary: `${seed.insured} paused for broker document chase.`,
      })
    case 'decisionReady':
      return deskCase({
        ...shared,
        completenessPct: 90 + (day % 8),
        recommendation: 'quote',
        decision: 'pending',
        signalScore: 74 + (day % 10),
        workflowStage: 2,
        packageDocNames: [
          `${seed.id}_Cyber_Application.pdf`,
          `${seed.id}_InfoSec_Questionnaire.pdf`,
          `${seed.id}_Incident_Response_Plan.pdf`,
          `${seed.id}_Loss_Runs.pdf`,
          `${seed.id}_Broker_Correspondence.pdf`,
        ],
        summary: `${seed.insured} is decision-ready after enrichment and evidence.`,
      })
    case 'referred':
      return deskCase({
        ...shared,
        completenessPct: 82 + (day % 10),
        recommendation: 'refer',
        decision: 'refer',
        signalScore: 50 + (day % 18),
        workflowStage: 2,
        summary: `${seed.insured} referred for specialist review.`,
      })
    case 'declined':
      return deskCase({
        ...shared,
        completenessPct: 80 + (day % 12),
        recommendation: 'decline',
        decision: 'decline',
        signalScore: 28 + (day % 20),
        workflowStage: 2,
        tier: 5,
        summary: `${seed.insured} declined — outside delegated appetite.`,
      })
    default: {
      const neverBucket: never = seed.bucket
      return neverBucket
    }
  }
}

const QUEUE_FILL_CASES: CyberCase[] = QUEUE_FILL_SEEDS.map(queueFillCase)

